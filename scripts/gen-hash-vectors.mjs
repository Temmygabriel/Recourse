#!/usr/bin/env node
// Generates the cross-language hash vectors and the Solidity fixture that
// asserts against them.
//
// WHY THIS EXISTS
//   The escrow commits `sha256(bytes(text))` over the text exactly as stored,
//   and the GenLayer judgment contract re-derives the same hash from the text
//   the relayer hands it. Those two implementations live in different languages
//   on different chains, and nothing in either one can detect that the other
//   started trimming whitespace: the escrow would still be internally
//   consistent, and the judgment contract would still reject every package —
//   leaving real disputes permanently unjudgeable.
//
//   So the vectors are the contract between the two. This script is the single
//   source: it writes the JSON that the Python test reads and the Solidity
//   literals that the Foundry test asserts against, so the two cannot drift
//   without CI noticing.
//
// Run:  node scripts/gen-hash-vectors.mjs
// CI:   runs this, then `git diff --exit-code` to prove the checked-in fixtures
//       match what the generator produces.

import { createHash } from 'node:crypto';
import { writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

const sha256Hex = (text) => createHash('sha256').update(text, 'utf8').digest('hex');

// The cases that matter are the ones where a well-meaning "cleanup" would change
// the bytes: leading/trailing whitespace, an interior newline or tab, an item
// whose own text ends in a space, and non-ASCII. A plain sentence would pass
// against a trimming implementation and prove nothing.
const STRINGS = [
  ['promise_simple', 'Deliver three illustrations.'],
  ['promise_trailing_newline', 'Deliver three illustrations.\n'],
  ['promise_leading_and_trailing_spaces', '  Deliver three illustrations.  '],
  ['promise_internal_double_space', 'Deliver three  illustrations.'],
  ['promise_unicode', "Livrer 3 illustrations \u{1F3A8} — prêtes pour l'impression."],
  ['promise_at_500_chars', 'a'.repeat(500)],
  ['promise_tab_and_newline', 'Deliver\tthree\nillustrations.'],
  ['delivery_notes_trailing_newline', 'Uploaded all files.\n'],
  ['dispute_notes_simple', 'Only two of three were delivered.'],
];

const RUBRICS = [
  ['rubric_three_items', ['Three illustrations at 3000px', 'Mobile versions', 'Layered source files']],
  ['rubric_item_with_embedded_newline', ['First line\nsecond line', 'Second criterion']],
  ['rubric_item_with_trailing_space', ['Criterion with trailing space ', 'Second criterion']],
  ['rubric_two_unicode_items', ['Épreuve \u{1F4C4}', 'Deuxième critère']],
];

// The join is a single newline, matching `_rubricHash` in the Solidity escrow
// and `_rubric_hash` in the judgment contract. A trailing newline between items
// would make the two hashes differ on every multi-item rubric.
const RUBRIC_JOIN = '\n';

const stringVectors = STRINGS.map(([name, text]) => ({ name, text, sha256: sha256Hex(text) }));
const rubricVectors = RUBRICS.map(([name, rubric]) => {
  const joined = rubric.join(RUBRIC_JOIN);
  return { name, rubric, joined, sha256: sha256Hex(joined) };
});

const json = {
  note:
    'Canonical hash vectors, generated by scripts/gen-hash-vectors.mjs. Both the Solidity escrow and the GenLayer judgment contract must reproduce every one of these. See docs/DATA_MODEL.md section 3. Do not edit by hand.',
  string_sha256: stringVectors,
  rubric_sha256: rubricVectors,
};

mkdirSync(join(ROOT, 'docs', 'vectors'), { recursive: true });
writeFileSync(
  join(ROOT, 'docs', 'vectors', 'hash-vectors.json'),
  JSON.stringify(json, null, 2) + '\n',
  'utf8',
);

// --- Solidity fixture ------------------------------------------------------
//
// Solidity string literals are raw UTF-8 with no \u escape, so non-ASCII is
// emitted as-is and only the control characters need escaping.

const esc = (s) =>
  s
    .replace(/\\/g, '\\\\')
    .replace(/"/g, '\\"')
    .replace(/\n/g, '\\n')
    .replace(/\t/g, '\\t')
    .replace(/\r/g, '\\r');

const lines = [];
lines.push('// SPDX-License-Identifier: MIT');
lines.push('pragma solidity 0.8.24;');
lines.push('');
lines.push('// GENERATED FILE — do not edit. Regenerate with:');
lines.push('//   node scripts/gen-hash-vectors.mjs');
lines.push('//');
lines.push('// The escrow must hash text exactly as stored. Every string below is a case');
lines.push('// where trimming, collapsing, or normalising would change the bytes — which');
lines.push('// would silently decouple this contract from the GenLayer judgment contract,');
lines.push('// because the two are the only implementations of this hash. See the header');
lines.push('// of scripts/gen-hash-vectors.mjs.');
lines.push('library HashVectors {');
lines.push('    struct StringVector {');
lines.push('        string name;');
lines.push('        string text;');
lines.push('        bytes32 digest;');
lines.push('    }');
lines.push('');
lines.push('    struct RubricVector {');
lines.push('        string name;');
lines.push('        string[] rubric;');
lines.push('        bytes32 digest;');
lines.push('    }');
lines.push('');
lines.push(`    function stringVectors() internal pure returns (StringVector[] memory v) {`);
lines.push(`        v = new StringVector[](${stringVectors.length});`);
stringVectors.forEach((vec, i) => {
  lines.push(`        v[${i}].name = "${esc(vec.name)}";`);
  lines.push(`        v[${i}].text = "${esc(vec.text)}";`);
  lines.push(`        v[${i}].digest = hex"${vec.sha256}";`);
});
lines.push('    }');
lines.push('');
lines.push('    function rubricVectors() internal pure returns (RubricVector[] memory v) {');
lines.push(`        v = new RubricVector[](${rubricVectors.length});`);
rubricVectors.forEach((vec, i) => {
  lines.push(`        v[${i}].name = "${esc(vec.name)}";`);
  lines.push(`        v[${i}].rubric = new string[](${vec.rubric.length});`);
  vec.rubric.forEach((item, j) => {
    lines.push(`        v[${i}].rubric[${j}] = "${esc(item)}";`);
  });
  lines.push(`        v[${i}].digest = hex"${vec.sha256}";`);
});
lines.push('    }');
lines.push('}');

mkdirSync(join(ROOT, 'contracts', 'test'), { recursive: true });
writeFileSync(join(ROOT, 'contracts', 'test', 'HashVectors.generated.sol'), lines.join('\n') + '\n', 'utf8');

console.log(
  `wrote docs/vectors/hash-vectors.json (${stringVectors.length} string, ${rubricVectors.length} rubric)`,
);
console.log('wrote contracts/test/HashVectors.generated.sol');
